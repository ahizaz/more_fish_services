String appText(String value) {
  var translated = value.tr;
  if (Get.locale?.languageCode != 'bn') return translated;

  const unitTranslations = {
    'mg/L': 'মিগ্রা/লিটার',
    'g / fish': 'গ্রাম / মাছ',
    'g / day': 'গ্রাম / দিন',
    ' kg': ' কেজি',
    ' fish': ' মাছ',
    ' ppt': ' পিপিটি',
    ' ppm': ' পিপিএম',
    ' ph': ' পিএইচ',
    '°C': '°সে.',
  };
  for (final entry in unitTranslations.entries) {
    translated = translated.replaceAll(entry.key, entry.value);
  }

  const bengaliDigits = '০১২৩৪৫৬৭৮৯';
  return translated.replaceAllMapped(
    RegExp(r'\d'),
    (match) => bengaliDigits[int.parse(match[0]!)],
  );
}
